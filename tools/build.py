"""Bundle audited local modules. Python 3.6+; no network or third-party packages."""
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
MODULES = ["CleanupManager", "SettingsManager", "NotificationManager", "UIController",
           "FeatureRegistry", "FeatureController", "Main"]


def build():
    chunks = ["-- VW MENU | independent client UI | generated by tools/build.py\n"
              "-- Put this entire file in ONE LocalScript in StarterPlayerScripts.\n"
              "-- No remote execution, key system or executor-specific API.\n"
              "local __modules = {}\nlocal __cache = {}\nlocal __require\n"]
    for name in MODULES:
        source = (ROOT / "src" / (name + ".lua")).read_text(encoding="utf-8-sig")
        source = re.sub(r"require\(script\.Parent\.(\w+)\)", r'__require("\1")', source)
        chunks.append('__modules["' + name + '"] = function()\n' + source + "\nend\n")
    chunks.append("__require = function(name)\n"
                  "    if __cache[name] ~= nil then return __cache[name] end\n"
                  "    local factory = assert(__modules[name], 'Missing module: ' .. tostring(name))\n"
                  "    local value = factory()\n    __cache[name] = value\n    return value\nend\n"
                  'return __require("Main").Start()\n')
    (ROOT / "VW_MENU.lua").write_text("\n".join(chunks), encoding="utf-8")

    # XML model imports as a Folder with ModuleScripts + the client bootstrap.
    # Import only into StarterPlayerScripts of an authorized test experience.
    model = ET.Element("roblox", {"version": "4"})
    folder = ET.SubElement(model, "Item", {"class": "Folder", "referent": "VWMenu"})
    props = ET.SubElement(folder, "Properties")
    ET.SubElement(props, "string", {"name": "Name"}).text = "VWMenu"
    for name in MODULES + ["Bootstrap.client"]:
        cls = "LocalScript" if name.endswith(".client") else "ModuleScript"
        item = ET.SubElement(folder, "Item", {"class": cls, "referent": "VWMenu_" + name})
        props = ET.SubElement(item, "Properties")
        ET.SubElement(props, "string", {"name": "Name"}).text = name.replace(".client", "")
        ET.SubElement(props, "ProtectedString", {"name": "Source"}).text = (
            ROOT / "src" / (name + ".lua")).read_text(encoding="utf-8-sig")
    ET.ElementTree(model).write(str(ROOT / "VW_MENU.rbxmx"), encoding="utf-8", xml_declaration=True)
    print("Built VW_MENU.lua and VW_MENU.rbxmx from {} modules".format(len(MODULES)))


if __name__ == "__main__":
    build()
